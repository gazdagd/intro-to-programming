public class Main {
    public static void main(String[] args) {
        int a = 5 + 3; // 8
        a = a + 5; // a = a + 5
        a += 5; // a = a + 5
        a -= 5; // a = a - 5
        a *= 5; // a = a * 5
        a /= 5; // a = a / 5
        a %= 5; // a = a % 5
        System.out.println(a);
    }
}